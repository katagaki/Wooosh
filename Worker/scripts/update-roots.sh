#!/bin/sh
# Regenerates src/roots/*.ts from the vendors' published trust anchors.
# Apple: the App Attestation root. TPM: the RootCA folders of Microsoft's
# TrustedTpm.cab, the set Windows itself trusts for EK certificates.
# Intermediates are not bundled; the client sends its own chain.
set -eu
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

curl -fsSL -o "$work/apple.pem" https://www.apple.com/certificateauthority/Apple_App_Attestation_Root_CA.pem
curl -fsSL -o "$work/TrustedTpm.cab" "https://go.microsoft.com/fwlink/?linkid=2097925"
mkdir "$work/tpm"
bsdtar -xf "$work/TrustedTpm.cab" -C "$work/tpm"

to_b64() {
  # Accepts DER or PEM; emits one-line base64 DER. Converted through a file
  # because a pipeline's status is the last command's, which hides a failed parse.
  openssl x509 -in "$1" -inform DER -outform DER -out "$work/one.der" 2>/dev/null \
    || openssl x509 -in "$1" -inform PEM -outform DER -out "$work/one.der" 2>/dev/null \
    || return 1
  base64 < "$work/one.der" | tr -d '\n'
}

{
  echo "// Generated by scripts/update-roots.sh. Do not edit."
  printf 'export const APPLE_APP_ATTEST_ROOT = "%s";\n' "$(to_b64 "$work/apple.pem")"
} > src/roots/apple.ts

{
  echo "// Generated by scripts/update-roots.sh. Do not edit."
  echo "export const TPM_ROOTS: string[] = ["
  find "$work/tpm" -path '*/RootCA/*' -type f | sort | while read -r f; do
    if b=$(to_b64 "$f" 2>/dev/null) && [ -n "$b" ]; then
      printf '  "%s",\n' "$b"
    else
      echo "skipping unreadable root: ${f#"$work"/tpm/}" >&2
    fi
  done
  echo "];"
} > src/roots/tpm.ts

echo "apple root: 1, tpm roots: $(grep -c '^  "' src/roots/tpm.ts)"
